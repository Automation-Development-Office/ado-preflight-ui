#!/usr/bin/env python3
"""Generate src/oidcClientDefaults.generated.mjs from the infra.ado collection.

The default OIDC client ID of Grafana, BookStack, NetBox, Quay, MinIO and Developer
Hub lives in ``components_defaults.yml`` in the collection. The form resolves a
blank client ID to that default exactly as the collection does, so this file is
generated from it rather than maintained by hand.

    python3 scripts/sync-oidc-client-defaults.py            # write
    python3 scripts/sync-oidc-client-defaults.py --check    # fail if out of date

The collection checkout defaults to ../ado; override with ADO_COLLECTION_DIR.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "oidcClientDefaults.generated.mjs"
COLLECTION = Path(os.environ.get("ADO_COLLECTION_DIR") or ROOT.parent / "ado")
VALIDATOR = COLLECTION / "roles" / "bootstrap_generate_env_vars" / "files" / "preflight_oidc.py"


def render(defaults):
    body = ",\n".join(f"  {key}: {json.dumps(value)}" for key, value in sorted(defaults.items()))
    return (
        "// GENERATED by scripts/sync-oidc-client-defaults.py from the infra.ado collection's\n"
        "// components_defaults.yml. Do not edit by hand; re-run the script.\n"
        "export const OIDC_DEFAULT_CLIENT_IDS = Object.freeze({\n"
        f"{body}\n"
        "});\n"
    )


def main():
    if not VALIDATOR.is_file():
        raise SystemExit(f"collection source not found: {VALIDATOR} (set ADO_COLLECTION_DIR)")
    result = subprocess.run(
        [sys.executable, str(VALIDATOR), "--print-default-client-ids"],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode:
        raise SystemExit(result.stderr or "could not read default client IDs")
    content = render(json.loads(result.stdout))
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != content:
            raise SystemExit(f"{OUT.name} is out of date; run scripts/sync-oidc-client-defaults.py")
        print(f"{OUT.name} is up to date")
        return
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
